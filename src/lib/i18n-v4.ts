export type V4Copy = { [K in keyof (typeof v4)["es"]]: string };

export function useV4() {
  const { lang } = useI18n();
  return { v: v4[lang] as V4Copy, lang };
}

export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
